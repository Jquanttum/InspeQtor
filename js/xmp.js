/*
 * Quanttum Photo Inspector — XMP reader (vanilla JS, no dependencies)
 *
 * A small non-validating XML tokenizer (no DOCTYPE / entity expansion, so no
 * XXE or "billion laughs" risk) plus an RDF/XMP walker. Produces a flat map of
 * properties ("xmp:CreatorTool" -> value), the edit history, derivation info,
 * Camera-Raw crop settings, and the IPTC DigitalSourceType label.
 */
(function (g) {
  'use strict';
  var QPI = g.QPI = g.QPI || {};

  var MAX_NODES = 60000, MAX_DEPTH = 80;

  function decodeEntities(s) {
    return s.replace(/&(#x[0-9a-fA-F]+|#[0-9]+|amp|lt|gt|quot|apos);/g, function (m, e) {
      switch (e) {
        case 'amp': return '&'; case 'lt': return '<'; case 'gt': return '>'; case 'quot': return '"'; case 'apos': return "'";
      }
      var cp = e.charAt(1) === 'x' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      if (!isFinite(cp) || cp > 0x10FFFF || cp === 0) return '�';
      try { return String.fromCodePoint(cp); } catch (err) { return '�'; }
    });
  }

  function parseXml(str) {
    var root = { name: '#root', attrs: {}, children: [], text: '' };
    var stack = [root], nodes = 0, truncated = false;
    var re = /<!--[\s\S]*?-->|<\?[\s\S]*?\?>|<!\[CDATA\[([\s\S]*?)\]\]>|<!DOCTYPE[^>]*>|<(\/?)([A-Za-z_][\w:.\-]*)((?:\s+[\w:.\-]+\s*=\s*(?:"[^"]*"|'[^']*'))*)\s*(\/?)>|([^<]+)/g;
    var m;
    while ((m = re.exec(str)) !== null) {
      if (m[1] !== undefined) { stack[stack.length - 1].text += m[1]; continue; }
      if (m[6] !== undefined) { stack[stack.length - 1].text += decodeEntities(m[6]); continue; }
      if (m[3] === undefined) continue; // comment / PI / DOCTYPE
      if (m[2] === '/') {
        if (stack.length > 1) stack.pop();
        continue;
      }
      if (++nodes > MAX_NODES || stack.length > MAX_DEPTH) { truncated = true; break; }
      var attrs = {}, ar = /([\w:.\-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g, am;
      while ((am = ar.exec(m[4] || '')) !== null) attrs[am[1]] = decodeEntities(am[2] !== undefined ? am[2] : am[3]);
      var node = { name: m[3], attrs: attrs, children: [], text: '' };
      stack[stack.length - 1].children.push(node);
      if (m[5] !== '/') stack.push(node);
    }
    root.truncated = truncated;
    return root;
  }

  function findAll(node, name, out) {
    out = out || [];
    for (var i = 0; i < node.children.length; i++) {
      var c = node.children[i];
      if (c.name === name) out.push(c);
      findAll(c, name, out);
    }
    return out;
  }

  function childNamed(node, names) {
    for (var i = 0; i < node.children.length; i++) if (names.indexOf(node.children[i].name) >= 0) return node.children[i];
    return null;
  }

  function structFrom(node) {
    var o = {}, k, any = false;
    for (k in node.attrs) {
      if (k === 'rdf:parseType' || k === 'rdf:about' || k.indexOf('xmlns') === 0) continue;
      o[k] = node.attrs[k]; any = true;
    }
    for (var i = 0; i < node.children.length; i++) {
      var c = node.children[i]; o[c.name] = valueOf(c); any = true;
    }
    return any ? o : null;
  }

  function valueOf(node) {
    var coll = childNamed(node, ['rdf:Seq', 'rdf:Bag', 'rdf:Alt']);
    if (coll) {
      var arr = [];
      for (var i = 0; i < coll.children.length; i++) if (coll.children[i].name === 'rdf:li') arr.push(valueOf(coll.children[i]));
      return arr;
    }
    var st = structFrom(node);
    if (st) {
      var t = node.text.trim();
      if (t && node.name === 'rdf:li' && Object.keys(st).length === 1 && st['xml:lang'] !== undefined) return t;
      return st;
    }
    return node.text.trim();
  }

  function parseGpsCoord(s) {
    if (typeof s !== 'string') return null;
    var m = /^\s*(\d+),(\d+(?:\.\d+)?)(?:,(\d+(?:\.\d+)?))?\s*([NSEWnsew])\s*$/.exec(s);
    if (!m) return null;
    var v = parseFloat(m[1]) + parseFloat(m[2]) / 60 + (m[3] ? parseFloat(m[3]) / 3600 : 0);
    var r = m[4].toUpperCase();
    return (r === 'S' || r === 'W') ? -v : v;
  }

  var DIGITAL_SOURCE = {
    trainedAlgorithmicMedia: 'Generated by a trained AI model',
    compositeWithTrainedAlgorithmicMedia: 'Composite including AI-generated elements',
    algorithmicMedia: 'Generated by an algorithm (non-AI)',
    digitalCapture: 'Digital capture (camera)',
    computationalCapture: 'Computational capture',
    negativeFilm: 'Scan of negative film', positiveFilm: 'Scan of positive film', print: 'Scan of a print',
    composite: 'Composite of multiple images', compositeCapture: 'Composite capture', screenCapture: 'Screen capture',
    virtualRecording: 'Virtual recording', softwareImage: 'Created by software', dataDrivenMedia: 'Data-driven media',
    humanEdits: 'Human edits', minorHumanEdits: 'Minor human edits', compositeSynthetic: 'Composite with synthetic elements',
    trainedAlgorithmicData: 'AI-generated data', algorithmicallyEnhanced: 'Algorithmically enhanced', other: 'Other'
  };

  function parseXmp(str) {
    var res = { props: {}, history: [], derivedFrom: null, creatorTool: null, crop: null, gps: null, digitalSourceType: null, parseTruncated: false, descriptions: 0 };
    var root = parseXml(str);
    res.parseTruncated = !!root.truncated;
    var descs = findAll(root, 'rdf:Description');
    res.descriptions = descs.length;
    descs.forEach(function (d) {
      var k;
      for (k in d.attrs) {
        if (k.indexOf('xmlns') === 0 || k === 'rdf:about') continue;
        if (!(k in res.props)) res.props[k] = d.attrs[k];
      }
      for (var i = 0; i < d.children.length; i++) {
        var c = d.children[i];
        if (!(c.name in res.props)) res.props[c.name] = valueOf(c);
      }
    });
    var p = res.props;
    res.creatorTool = typeof p['xmp:CreatorTool'] === 'string' ? p['xmp:CreatorTool'] : null;
    var h = p['xmpMM:History'];
    if (Array.isArray(h)) {
      res.history = h.map(function (e) {
        if (!e || typeof e !== 'object') return { raw: String(e) };
        return { action: e['stEvt:action'] || '', when: e['stEvt:when'] || '', softwareAgent: e['stEvt:softwareAgent'] || '', changed: e['stEvt:changed'] || '', instanceID: e['stEvt:instanceID'] || '', parameters: e['stEvt:parameters'] || '' };
      });
    }
    if (p['xmpMM:DerivedFrom'] && typeof p['xmpMM:DerivedFrom'] === 'object') res.derivedFrom = p['xmpMM:DerivedFrom'];
    if (p['crs:HasCrop'] !== undefined || p['crs:CropLeft'] !== undefined) {
      res.crop = { hasCrop: String(p['crs:HasCrop']).toLowerCase() === 'true', left: parseFloat(p['crs:CropLeft']), top: parseFloat(p['crs:CropTop']), right: parseFloat(p['crs:CropRight']), bottom: parseFloat(p['crs:CropBottom']), angle: parseFloat(p['crs:CropAngle']) };
    }
    var lat = parseGpsCoord(p['exif:GPSLatitude']), lon = parseGpsCoord(p['exif:GPSLongitude']);
    if (lat !== null || lon !== null) res.gps = { lat: lat, lon: lon };
    var dst = p['Iptc4xmpExt:DigitalSourceType'];
    if (typeof dst === 'string' && dst) {
      var key = dst.replace(/^.*[\/#]/, '');
      res.digitalSourceType = { uri: dst, key: key, label: DIGITAL_SOURCE[key] || key };
    }
    return res;
  }

  function extractPacket(u8, seg) {
    // seg.dataOffset points at the namespace id ("http://ns.adobe.com/xap/1.0/\0"); the packet follows the NUL.
    var s = seg.dataOffset, e = seg.dataOffset + seg.dataLength, i = s;
    while (i < e && u8[i] !== 0) i++;
    i++;
    if (i >= e) return '';
    var bytes = u8.subarray(i, e);
    if (typeof TextDecoder !== 'undefined') {
      try { return new TextDecoder('utf-8').decode(bytes); } catch (err) { /* fall through */ }
    }
    var out = '';
    for (var j = 0; j < bytes.length; j++) out += String.fromCharCode(bytes[j]);
    return out;
  }

  QPI.xmp = { parseXmp: parseXmp, parseXml: parseXml, extractPacket: extractPacket, parseGpsCoord: parseGpsCoord, DIGITAL_SOURCE: DIGITAL_SOURCE };
  if (typeof module !== 'undefined' && module.exports) module.exports = QPI.xmp;
})(typeof window !== 'undefined' ? window : globalThis);
