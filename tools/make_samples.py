#!/usr/bin/env python3
"""Generate the bundled demo photo (samples/demo_cropped_keeps_thumbnail.jpg and js/samples.js).

The demo is the synthetic test fixture t_chelsea_crop_c60 (tests/make_fixtures.py): the scikit-image
'chelsea' cat photograph (CC0 public-domain dedication, Stefan van der Walt) with a central 60% crop as the
main image and the ORIGINAL uncropped frame kept as the EXIF thumbnail. Camera, time and GPS-free EXIF are
synthetic. Run tests/make_fixtures.py first.
"""
import base64, os, shutil
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'tests', 'fixtures', 't_chelsea_crop_c60.jpg')
name = 'demo_cropped_keeps_thumbnail.jpg'
os.makedirs(os.path.join(root, 'samples'), exist_ok=True)
shutil.copy(src, os.path.join(root, 'samples', name))
b64 = base64.b64encode(open(src, 'rb').read()).decode()
open(os.path.join(root, 'js', 'samples.js'), 'w').write(
    '/* Demo photo bundled for the "Load demo photo" button (generated by tools/make_samples.py). */\n'
    'window.QPI = window.QPI || {};\nwindow.QPI.samples = [{ name: %r, b64: %r }];\n' % (name, b64))
print('wrote samples/%s and js/samples.js (%d bytes base64)' % (name, len(b64)))
